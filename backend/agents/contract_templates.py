def get_all_categories() -> List[Dict[str, Any]]:
    result = []
    for cat in CONTRACT_CATEGORIES:
        cat_dict = {
            "id": cat.id,
            "name": cat.name,
            "description": cat.description,
            "icon": cat.icon,
            "color": cat.color,
            "subcategories": [],
            "template_count": 0,
        }
        for sub in cat.subcategories:
            templates_summary = []
            for tid in sub.template_ids:
                t = CONTRACT_TEMPLATES.get(tid)
                if t:
                    templates_summary.append({
                        "id": t.id,
                        "name": t.name,
                        "description": t.description,
                        "field_count": len(t.fields),
                    })
            sub_dict = {
                "id": sub.id,
                "name": sub.name,
                "description": sub.description,
                "icon": sub.icon,
                "template_ids": sub.template_ids,
                "template_count": len(sub.template_ids),
                "templates": templates_summary,
            }
            cat_dict["subcategories"].append(sub_dict)
            cat_dict["template_count"] += len(sub.template_ids)
        result.append(cat_dict)
    return result


def get_template_by_id(template_id: str) -> Optional[ContractTemplate]:
    return CONTRACT_TEMPLATES.get(template_id)


def get_templates_by_subcategory(subcategory_id: str) -> List[ContractTemplate]:
    return [t for t in CONTRACT_TEMPLATES.values() if t.subcategory_id == subcategory_id]


def search_templates(keyword: str) -> List[ContractTemplate]:
    keyword_lower = keyword.lower()
    results = []
    for t in CONTRACT_TEMPLATES.values():
        if (keyword_lower in t.name.lower() or
            keyword_lower in t.description.lower() or
            keyword_lower in t.category_id.lower() or
            any(keyword_lower in f.label.lower() for f in t.fields)):
            results.append(t)
    return results


def template_to_dict(t: ContractTemplate) -> Dict[str, Any]:
    return {
        "id": t.id,
        "name": t.name,
        "description": t.description,
        "category_id": t.category_id,
        "subcategory_id": t.subcategory_id,
        "fields": [
            {
                "key": f.key,
                "label": f.label,
                "field_type": f.field_type,
                "required": f.required,
                "placeholder": f.placeholder,
                "options": f.options,
                "default_value": f.default_value,
            }
            for f in t.fields
        ],
        "outline_sections": t.outline_sections,
        "prompt_template": t.prompt_template,
        "law_references": t.law_references,
    }
