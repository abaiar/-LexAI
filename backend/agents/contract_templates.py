from typing import Dict, List, Any, Optional
from dataclasses import dataclass, field


@dataclass
class TemplateField:
    key: str
    label: str
    field_type: str = "text"
    required: bool = True
    placeholder: str = ""
    options: List[str] = field(default_factory=list)
    default_value: str = ""


@dataclass
class ContractTemplate:
    id: str
    name: str
    description: str
    category_id: str
    subcategory_id: str
    fields: List[TemplateField]
    outline_sections: List[str]
    prompt_template: str
    law_references: List[str] = field(default_factory=list)


